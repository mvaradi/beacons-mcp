"""Checks on the built viewer page (src/beacons_mcp/ui/viewer.html).

The page is generated by `npm run build` in viewer/ and is not committed, so these
tests are skipped until it has been built.
"""

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).parent.parent
PAGE = ROOT / "src" / "beacons_mcp" / "ui" / "viewer.html"

pytestmark = pytest.mark.skipif(
    not PAGE.is_file(),
    reason="viewer not built: run `npm install && npm run build` in viewer/",
)


@pytest.fixture(scope="module")
def html() -> str:
    return PAGE.read_text(encoding="utf-8")


def test_it_is_one_self_contained_html_document(html):
    assert html.lstrip().lower().startswith("<!doctype html>")
    assert html.count("<html") == 1
    assert '<script type="module"' in html


def test_it_needs_no_outside_website(html):
    # No external scripts, stylesheets, images or frames, and no CSS imports from the network.
    external = [
        url
        for url in re.findall(
            r"<(?:script|link|img|iframe|source)\b[^>]*\b(?:src|href)=[\"']([^\"']+)",
            html,
        )
        if not url.startswith(("data:", "#", "blob:"))
    ]
    assert external == []
    assert not re.search(r"@import|url\(\s*[\"']?https?:", html)


def test_it_does_not_contain_the_mp4_encoder_that_a_sandbox_blocks(html):
    # Its start-up fetches a data: URL, which an app sandbox's CSP refuses (the page then
    # never starts). The build replaces it with a stub; see viewer/vite.config.js.
    assert "data:application/wasm;base64" not in html
    assert (
        "h264-mp4-encoder" not in html.lower() or "MP4 export is not available" in html
    )


def test_it_keeps_the_licence_notices_of_what_it_bundles(html):
    top = html[:20_000]
    assert "Third-party notices" in top
    assert (
        top.count("Permission is hereby granted") >= 1
    )  # the MIT text, kept as required
    assert "molstar" in top and "@modelcontextprotocol/ext-apps" in top


def test_it_stays_a_reasonable_size(html):
    assert len(html.encode("utf-8")) < 8 * 1024 * 1024
